/**
 * 空态用的图标 —— 与 `NavIcon` **同一套图形**，只是放大渲染。
 *
 * 【为什么不另画几个】空态原计划新增 3–4 个图标，但把清单过了一遍之后发现：
 *   空态要表达的概念（没有资料 / 没有投稿 / 没有问答记录 / 没有账号 / 没有数据集…）
 *   与导航项**完全重合**，上面这 20 个已经覆满了，一个新图形都不用加。
 *   而且复用还有一个更重要的好处：**同一个概念在侧栏和空态里长得一样**。
 *   另画一套的话，"没有投稿记录"旁边那个图标与侧栏「投稿台账」的图标不同，
 *   用户要多学一次"这两个说的是同一件事"。
 *
 * 【描边为什么变细】`NavIcon` 是 15px 配 1.7 的描边，放大到 34px 再看就偏粗、
 *   偏沉，与"淡淡的一个提示"这个定位不符。所以按尺寸反比调细到 1.3 ——
 *   视觉重量大致不变，放大只是变清楚，不是变重。
 */
export function NavGlyph({ name, size = 34 }: { name: NavIconName; size?: number }) {
  return (
    <svg
      className="empty-glyph"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="1.3"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      {PATHS[name]}
    </svg>
  );
}

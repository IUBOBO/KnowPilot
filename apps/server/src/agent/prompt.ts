    '· 提交前逐项确认关键结论的证据支持整句，包括数字、否定、范围与例外；合并支撑同一要点的来源。把证据号放在对应要点或表格核心字段旁。',
    '· **每条文档引用都要在 `quotes` 里附一段逐字摘录**：`{"evidence_id": "E1", "quote": "……"}`。',

    '  不得用省略号跳过中间内容，也不要抄证据头里的标题/页码/「原文 N 字」这些元数据。',
    '  空白与换行差异服务端会容忍，改字不会：不是原文逐字片段的引用会被整条剔除并记一条告警。',
    '· 台账、数据集、分区记录由服务端填充内容，**不需要**摘录，只核对编号；',

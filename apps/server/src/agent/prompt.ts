/**
 * 拼装好的 system prompt 的 sha256（hex）。
 *
 * 【这个哈希与设计文档里的 `PromptPlan.hash` 不是一回事 —— 必须写清】
 *   03 号 §5 要求 Trace 记 `PromptPlan.hash`。但全仓**没有 `PromptPlan`** ——
 *   那套 `{ blocks[], hash, totalBytes }` 结构只在 02 号 §7.2 提过，从未落成代码，
 *   `ask-run.ts` 里只有一个拼好的字符串。所以这里对**那段字符串**取 sha256。
 *   它够用：改一个字，哈希就变，于是"哪次评测跑的是旧版提示词"一眼可辨 ——
 *   这正是 hash 要干的事。但它**不等于**规格里的 `PromptPlan.hash`（没有分块信息）。
 *
 * 【O11 之后它只代表"这一次运行"的那段字符串】场景规则按问题注入，因此两次
 *   不同的问答可以有不同的 hash。要比较提示词版本，请用不带 route/question 的
 *   核心段哈希。
 */
export function promptHashOf(systemPrompt: string): string {
  return createHash('sha256').update(systemPrompt, 'utf8').digest('hex');
}

/**
 * 一条知识要落成什么 markdown。**入库与冲突检测共用这一个函数**。
 *
 * 【为什么必须共用，而不是各写一份】入库时 `admit.ts` 拿它当文件内容；
 *   冲突检测时把**待确认的这条**也渲染成同样的形态去算向量。两侧不同形的话，
 *   比较就变成"正文 ↔ 带标题和来源行的块文本"，于是：
 *     · 完全相同的两条知识算出来不是 1.0（实测约 0.93），
 *     · 阈值实际卡在哪儿取决于那段脚手架有多长，而不是取决于两条知识像不像。
 *   这个偏差是**静默的** —— 不报错、结果不崩，只是阈值悄悄偏了。共用一份
 *   渲染逻辑是唯一能把它消灭在构造上的办法。
 */
import type { KnowledgeEntry } from '@knowpilot/shared';
import { knowledgeTitle } from '@knowpilot/shared';

/**
 * 渲染成入库用的 markdown。
 *
 * 【为什么第一行不加 `# `】这一条是**踩出来的**，不是审美选择：`.md` 的解析器
 *   会把 `# 标题` 的 `# ` 去掉再切块，所以索引里那份块文本的第一行是**没有 `# `** 的。
 *   而冲突检测要在"待确认的知识"与"已入库的块文本"之间比相似度 —— 若这里保留 `# `，
 *   两侧就差了这两个字符，**完全相同的两条知识也只能算出约 0.93**，阈值实际卡在
 *   哪儿取决于这个前缀，而不是取决于两条知识像不像。
 *   代价是原件那份 .md 少了个 markdown 标题语法。可以接受：标题本来就是正文的首句
 *   （见 `knowledgeTitle`），下载下来照样一眼能认；而冲突检测的准确性更值钱。
 *
 * 【为什么要带 kind 与来源这两行】都不是装饰：
 *   1. `chunk.ts` 的 `MIN_CHUNK_CHARS = 80` 会把过短的块并走。极短的一条知识
 *      （"本组 8 卡 A100"）单靠正文只有十几个字，加上标题与这行上下文才站得住，
 *      不至于在块合并里被揉进别的块。
 *   2. 检索命中的片段会直接展示给人看。只看到一句孤零零的正文，没人知道
 *      它是"事实"还是"未决事项"—— 而这决定了它该怎么被采信。
 *
 * 这行**不写是谁说的**：谁提交的在条目上有记录，不该跟着知识正文一起进了
 * 别人能搜到的地方。
 *
 * 【改这个函数时要注意】它的输出会**被切块**（不是原样进索引）。任何在这里加上的
 *   行内标记（`#`、`*`、`-` …）都可能被解析器改写，而改写会让上面那个"两侧同形"
 *   的保证失效。改完请跑 `KNOWLEDGE_CHECK_REAL_MODEL=1 npm run verify-knowledge`
 *   —— 它里面有一条"完全相同的两条应当 ≈1.0"的断言，专门盯着这件事。
 */
export function renderKnowledgeMarkdown(entry: Pick<KnowledgeEntry, 'kind' | 'content'>): string {
  // 【结尾不留空行，同样是踩出来的】解析器切出来的块文本结尾没有换行。
  //   这里多一个 `\n`，完全相同的两条知识就只算出 0.987（实测），
  //   而那 0.012 的差白送给一个没有意义的分隔符。去掉之后两侧逐字节相同。
  return [
    knowledgeTitle(entry.content, entry.kind),
    '',
    `> 来源：知识沉淀（${entry.kind}）`,
    '',
    entry.content.trim(),
  ].join('\n');
}
